# 长名优先，避免“吉林”先于“吉林市”之类的歧义；同长度保持表内顺序
_BY_LENGTH = sorted(COMMON_CITIES, key=len, reverse=True)


def find_city(text: str | None) -> str:
    """返回文本中最先出现的常见城市；没有时返回空串。"""
    content = (text or "").strip()
    if not content:
        return ""
    found = [(content.find(city), -len(city), city) for city in _BY_LENGTH if city in content]
    return min(found)[2] if found else ""


def normalize_city(name: str | None) -> str:
    """“苏州市” → “苏州”；不在词表中的城市原样保留（去掉“市”）。"""
    city = (name or "").strip()
    if city.endswith(CITY_SUFFIX) and len(city) > len(CITY_SUFFIX) + 1:
        city = city[: -len(CITY_SUFFIX)]
    return city


def place_in_city(place: str | None, city: str | None) -> bool:
    """车站/机场名是否属于该城市：包含城市名即可（“苏州园区”属于“苏州”）。"""
    target = normalize_city(city)
    return bool(target) and target in (place or "")
